package llmverify

import chisel3._
import chisel3.util._
import chiselFv._

/**
 * A counter module that tests reset behavior.
 * The counter increments on every clock cycle when enabled.
 * When reset is asserted (sync reset via reset IO), the counter returns to 0.
 */
class ResetCounter extends Module with Formal {
  val io = IO(new Bundle {
    val enable    : Bool = Input(Bool())
    val count     : UInt = Output(UInt(8.W))
    val wrap      : Bool = Output(Bool())
    val max_count : UInt = Input(UInt(8.W))
  })

  val counter = RegInit(0.U(8.W))
  val maxVal  = io.max_count

  when(io.enable) {
    when(counter >= maxVal) {
      counter := 0.U
    } .otherwise {
      counter := counter + 1.U
    }
  }

  io.count := counter
  io.wrap  := io.enable && (counter >= maxVal)

  // ── Formal Verification Assertions ──

  // Safety 1: After reset, counter must be 0.
  // At any cycle, if we assert the reset signal... but in Chisel, reset is
  // built-in via RegInit(0.U). The `reset` signal is an implicit Bool in
  // the Module context, driven outside. We can verify the invariant that
  // when the implicit reset is asserted, the counter goes to 0.
  //
  // In formal verification, `reset` is the implicit hardware reset.
  // We use `assertAt(0.U, ...)` to check that after reset release, counter is 0.
  // Simpler: assert that after reset, counter is 0.
  fvAssert(past(reset.asBool, 1, peek = true) && !reset.asBool === counter === 0.U,
    "After reset_deasserted_counter_is_0")

  // Safety 2: Counter never exceeds maxVal + 1.
  fvAssert(counter <= maxVal + 1.U, "Counter_within_bounds")

  // Safety 3: When enable is low, counter stays unchanged.
  // Using ChiselFV stability assertion.
  assertStableWhen(!io.enable, counter, "Counter_stable_when_disabled")

  // Safety 4: When enable is high and counter < maxVal, counter increments by 1 next cycle.
  // Use implication with delay.
  assertImpliesDelay(io.enable && (counter < maxVal), counter === past(counter, 1, peek = true) + 1.U, 1,
    "Counter_increments_when_enabled")

  // Safety 5: Mutual exclusion - counter cannot both wrap and be at maxVal at the same time
  // (wrap is defined when counter >= maxVal, so both can be true simultaneously.
  // Actually wrap means the counter wraps around, so let's use a different property)
  // When wrap fires, next cycle counter should be 0.
  assertNextStepWhen(io.wrap, counter === 0.U, "Wrap_resets_counter")

  // Safety 6: Past value stability - counter should never have unknown/undefined transitions
  // (this is more of a liveness/progress check - counter should eventually count)
  // Assert that when enabled, counter is monotonic (increasing) unless wrapping
  // This is actually already covered by safety 4.

  // Liveness: When enabled, counter should eventually wrap (reach maxVal and reset)
  // Use relaxed liveness - request is enable, response is wrap
  astRelaxedLiveness(io.enable, io.wrap, 300, "Enable_eventually_causes_wrap")
}

/**
 * Top-level module generated by VerilogGenerator.
 * Contains the ResetCounter module.
 */
object VerilogGenerator extends App {
  // Generate Verilog for the ResetCounter module
  (new chisel3.stage.ChiselStage).emitVerilog(
    new ResetCounter,
    Array("--target-dir", if (args.length > 1) args(1) else "generated")
  )
}
